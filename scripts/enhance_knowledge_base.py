def enhance_pest(filename, data):
    """增强单个害虫的知识库数据"""
    key = filename.replace(".json", "")

    if key not in ENHANCED:
        print(f"  ⏭️  跳过（无增强数据）: {filename}")
        return False

    enhance = ENHANCED[key]

    data["features"] = enhance["features"]
    data["symptoms"] = enhance["symptoms"]
    data["occurrence"] = enhance["occurrence"]
    data["prevention"] = enhance["prevention"]
    data["qa"] = enhance["qa"]

    print(f"  ✅ 已增强: {data['zh_name']} ({len(enhance['features'])}特征, {len(enhance['symptoms'])}症状, {len(enhance['occurrence'])}发生, {len(enhance['prevention'])}防治, {len(enhance['qa'])}问答)")
    return True


